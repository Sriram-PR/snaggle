#!/usr/bin/env bash
# Builds the QuickJS `qjs` interpreter for Android. yt-dlp runs it to solve YouTube's
# JS challenges (`qjs --script <file>`).
#
# Output: native/out/<abi>/libqjs.so (an executable named lib*.so so Android extracts it
# into nativeLibraryDir, the only place an app may exec from).
#
# Usage: native/quickjs/build.sh [abi...]   (default: arm64-v8a x86_64)
# Env:   ANDROID_NDK_HOME (default: $ANDROID_HOME/ndk/28.2.13676358)
set -euo pipefail

QJS_VERSION=2026-06-04
# bellard.org publishes no signatures or checksums; pinned from the first download.
QJS_SHA256=b376e839b322978313d929fd20663b11ba58b75df5a46c126dd19ea2fa70ad2a
API=24

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WORK="$ROOT/native/.build/quickjs"
OUT="$ROOT/native/out"
NDK="${ANDROID_NDK_HOME:-${ANDROID_HOME:-$HOME/Android/Sdk}/ndk/28.2.13676358}"
TOOLCHAIN="$NDK/toolchains/llvm/prebuilt/linux-x86_64"
ABIS=("${@:-arm64-v8a x86_64}")
read -r -a ABIS <<< "${ABIS[*]}"

mkdir -p "$WORK"
TARBALL="$WORK/quickjs-$QJS_VERSION.tar.xz"
if [ ! -f "$TARBALL" ]; then
    curl -fsSL -o "$TARBALL.tmp" "https://bellard.org/quickjs/quickjs-$QJS_VERSION.tar.xz"
    mv "$TARBALL.tmp" "$TARBALL"
fi
echo "$QJS_SHA256  $TARBALL" | sha256sum -c --quiet

SRC="$WORK/src"
rm -rf "$SRC" && mkdir -p "$SRC"
tar -xf "$TARBALL" -C "$SRC" --strip-components=1

# repl.c is bytecode generated by a host-built qjsc.
make -C "$SRC" -j"$(nproc)" repl.c >/dev/null

SOURCES=(qjs.c repl.c quickjs.c dtoa.c libregexp.c libunicode.c cutils.c quickjs-libc.c)
for ABI in "${ABIS[@]}"; do
    case "$ABI" in
        arm64-v8a) TRIPLE=aarch64-linux-android ;;
        x86_64)    TRIPLE=x86_64-linux-android ;;
        *) echo "Unsupported ABI: $ABI" >&2; exit 1 ;;
    esac
    CC="$TOOLCHAIN/bin/$TRIPLE$API-clang"
    OBJ="$SRC/obj-$ABI"
    mkdir -p "$OBJ" "$OUT/$ABI"
    for f in "${SOURCES[@]}"; do
        "$CC" -O2 -fwrapv -fPIE -D_GNU_SOURCE -DCONFIG_VERSION="\"$QJS_VERSION\"" \
            -c "$SRC/$f" -o "$OBJ/${f%.c}.o" &
    done
    wait
    "$CC" -pie -Wl,-z,max-page-size=16384 -o "$OBJ/qjs" "$OBJ"/*.o -lm -ldl
    "$TOOLCHAIN/bin/llvm-strip" -o "$OUT/$ABI/libqjs.so" "$OBJ/qjs"
    printf '%s\n' "$QJS_VERSION" > "$OUT/$ABI/quickjs.version"
done

# Every LOAD segment must be 16 KB aligned for Android 15+ 16 KB-page devices.
for ABI in "${ABIS[@]}"; do
    f="$OUT/$ABI/libqjs.so"
    if "$TOOLCHAIN/bin/llvm-readelf" -lW "$f" | awk '/LOAD/ && $NF != "0x4000" { bad=1 } END { exit bad }'; then
        echo "ok (16 KB aligned): $f ($(du -h "$f" | cut -f1))"
    else
        echo "NOT 16 KB aligned: $f" >&2; exit 1
    fi
done
